#!/usr/bin/env python3
"""Parity test (SLC-1): the engine built here against Orca Slicer's own program, same version, same project, G-code line by line.

    python parity.py --orca-cli <orca-slicer> --orca <orca checkout> --slice-3mf <build>/orca_core_slice_3mf  [--cases a,b,c] [--work <dir>]

For every case (a model and some settings):
  1. Orca's program reads the model, with the vendor presets resolved by tools/resolve_presets.py (Elegoo Centauri Carbon 0.4 nozzle,
     0.20mm Standard, Elegoo PLA unless the case says otherwise), and writes a 3MF that holds the model as placed and every setting.
  2. Orca's program slices that 3MF            -> the reference G-code.
  3. orca_core_slice_3mf slices the same 3MF   -> our G-code.
  4. The two are compared. Not compared: the line with the date, and the settings listing at the end of the file (`; key = value`
     after CONFIG_BLOCK_START): Orca's window adds a few keys of its own there (print host, plugins) that are not slicing settings.
The same 3MF goes to both programs on purpose: Orca reading an OBJ or STL directly and Orca reading its own 3MF can differ (the 3MF stores
the mesh as text with limited digits), and that difference is Orca's, not the engine's.

Exit code 0 when every case is identical.

Environment for Orca's program on Linux (an extracted AppImage): APPDIR, LD_LIBRARY_PATH and LC_ALL=C are taken from the environment as they are.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RESOLVE = os.path.join(os.path.dirname(HERE), "tools", "resolve_presets.py")

MACHINE = "Elegoo Centauri Carbon 0.4 nozzle"
PROCESS = "0.20mm Standard @Elegoo CC 0.4 nozzle"
FILAMENT = "Elegoo PLA @ECC"

# name: (model file relative to <orca>/tests/data, {setting: value} overrides of the process preset, filament preset)
CASES = {
    "cube":          ("cube",                 {}, FILAMENT),     # generated here: 20 mm cube
    "bridge":        ("bridge.obj",           {}, FILAMENT),
    "concave_hole":  ("cube_with_concave_hole.obj", {}, FILAMENT),
    "sloping_hole":  ("sloping_hole.obj",     {}, FILAMENT),
    "overhang":      ("overhang.obj",         {}, FILAMENT),
    "frog_legs":     ("frog_legs.obj",        {}, FILAMENT),
    "overhang_tree_support": ("overhang.obj", {"enable_support": "1", "support_type": "tree(auto)"}, FILAMENT),
    "overhang_normal_support": ("overhang.obj", {"enable_support": "1", "support_type": "normal(auto)"}, FILAMENT),
    "frog_gyroid_4walls": ("frog_legs.obj",   {"sparse_infill_pattern": "gyroid", "wall_loops": "4", "sparse_infill_density": "25%"}, FILAMENT),
    "frog_classic_walls": ("frog_legs.obj",   {"wall_generator": "classic", "seam_position": "random"}, FILAMENT),
    "frog_fuzzy":    ("frog_legs.obj",        {"fuzzy_skin": "external"}, FILAMENT),   # random in Orca itself: compared by totals (RANDOM)
    "overhang_petg": ("overhang.obj",         {}, "Elegoo PETG @ECC"),
    "frog_ironing":  ("frog_legs.obj",        {"ironing_type": "top"}, FILAMENT),
    "frog_spiral":   ("frog_legs.obj",        {"spiral_mode": "1"}, FILAMENT),
}


# Cases where Orca's own output is not the same from one run to the next (random noise in the toolpaths). Orca against Orca differs there,
# so the comparison is by totals: the layer count and the filament used, within the tolerance.
RANDOM = {"frog_fuzzy": 0.02}


def totals(path):
    """(layer count, filament used in mm) from the G-code's own summary lines."""
    layers = used = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("; total layer number:"):
                layers = int(line.split(":")[1])
            elif line.startswith("; filament used [mm] ="):
                used = float(line.split("=")[1].split(",")[0])
    return layers, used


def write_cube(path, size=20.0):
    import struct
    v = [(x, y, z) for z in (0, size) for y in (0, size) for x in (0, size)]
    tris = []
    for a, b, c, d in ((0, 2, 3, 1), (4, 5, 7, 6), (0, 1, 5, 4), (2, 6, 7, 3), (0, 4, 6, 2), (1, 3, 7, 5)):
        tris += [(v[a], v[b], v[c]), (v[a], v[c], v[d])]
    with open(path, "wb") as f:
        f.write(b"\0" * 80)
        f.write(struct.pack("<I", len(tris)))
        for t in tris:
            f.write(struct.pack("<3f", 0, 0, 0))
            for p in t:
                f.write(struct.pack("<3f", *p))
            f.write(b"\0\0")


def normalise(path):
    """The G-code lines that are compared: everything but the date line and the settings listing."""
    out = []
    in_config = False
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("; generated by"):
                continue
            if line.startswith("; CONFIG_BLOCK_START"):
                in_config = True
            if line.startswith("; CONFIG_BLOCK_END"):
                in_config = False
                continue
            if in_config:
                continue
            out.append(line)
    return out


def run(cmd, log, cwd, env=None, timeout=1800):
    with open(log, "wb") as lf:
        r = subprocess.run(cmd, cwd=cwd, env=env, stdout=lf, stderr=subprocess.STDOUT, timeout=timeout)
    return r.returncode


def resolve(profiles, work, process_overrides, filament):
    os.makedirs(work, exist_ok=True)
    subprocess.run([sys.executable, RESOLVE, profiles, work, MACHINE, PROCESS, filament], check=True, capture_output=True)
    pj = os.path.join(work, "process.json")
    with open(pj, encoding="utf-8") as f:
        d = json.load(f)
    d.update(process_overrides)
    with open(pj, "w", encoding="utf-8") as f:
        json.dump(d, f, indent=1)
    return [os.path.join(work, n) for n in ("machine.json", "process.json", "filament.json")]


def one_case(name, args):
    model, overrides, filament = CASES[name]
    work = os.path.join(args.work, name)
    shutil.rmtree(work, ignore_errors=True)
    os.makedirs(work)
    if model == "cube":
        model_path = os.path.join(work, "cube.stl")
        write_cube(model_path)
    else:
        model_path = os.path.join(args.orca, "tests", "data", model)
    machine, process, fil = resolve(os.path.join(args.orca, "resources", "profiles", "Elegoo"), work, overrides, filament)
    env = dict(os.environ)
    cli = [args.orca_cli, "--datadir", os.path.join(work, "datadir")]
    # 1. the project file
    p1 = os.path.join(work, "step1")
    os.makedirs(p1)
    rc = run(cli + ["--load-settings", machine + ";" + process, "--load-filaments", fil, "--export-3mf", "project.3mf", "--slice", "0",
                    "--outputdir", p1, model_path], os.path.join(work, "orca_step1.log"), work, env)
    project = os.path.join(p1, "project.3mf")
    if rc != 0 or not os.path.isfile(project):
        return "ORCA FAILED (step 1, code %s; see %s)" % (rc, work)
    # 2. Orca slices the project
    p2 = os.path.join(work, "step2")
    os.makedirs(p2)
    rc = run(cli + ["--slice", "0", "--outputdir", p2, project], os.path.join(work, "orca_step2.log"), work, env)
    ref = os.path.join(p2, "plate_1.gcode")
    if rc != 0 or not os.path.isfile(ref):
        return "ORCA FAILED (step 2, code %s; see %s)" % (rc, work)
    # 3. the engine slices the project
    ours = os.path.join(work, "ours.gcode")
    env2 = dict(env)
    env2["ORCA_CORE_RESOURCES"] = os.path.join(args.orca, "resources")
    rc = run([args.slice_3mf, project, ours], os.path.join(work, "ours.log"), work, env2)
    if rc != 0 or not os.path.isfile(ours):
        return "ENGINE FAILED (code %s; see %s/ours.log)" % (rc, work)
    if name in RANDOM:
        (la, ua), (lb, ub) = totals(ref), totals(ours)
        ok = la == lb and ua and ub and abs(ua - ub) <= RANDOM[name] * ua
        return ("SAME TOTALS (random in Orca itself): %s layers, %.0f vs %.0f mm of filament" if ok else
                "DIFFERENT TOTALS: %s layers vs %s, %s vs %s mm") % ((la, ua, ub) if ok else (la, lb, ua, ub))
    a, b = normalise(ref), normalise(ours)
    diff = [(i + 1, x, y) for i, (x, y) in enumerate(zip(a, b)) if x != y]
    if not diff and len(a) == len(b):
        return "IDENTICAL (%d lines)" % len(a)
    msg = "DIFFERENT: %d vs %d lines, %d differ" % (len(a), len(b), len(diff))
    for i, x, y in diff[:5]:
        msg += "\n      line %d\n        orca: %s\n        ours: %s" % (i, x[:140], y[:140])
    return msg


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--orca-cli", required=True)
    ap.add_argument("--orca", required=True, help="the Orca checkout (tests/data, resources/profiles)")
    ap.add_argument("--slice-3mf", required=True)
    ap.add_argument("--cases", default=",".join(CASES))
    ap.add_argument("--work", default=os.path.join(os.getcwd(), "parity_work"))
    args = ap.parse_args()
    bad = 0
    for name in args.cases.split(","):
        if name not in CASES:
            print("unknown case", name)
            return 2
        res = one_case(name, args)
        print("%-26s %s" % (name, res), flush=True)
        if not res.startswith(("IDENTICAL", "SAME TOTALS")):
            bad += 1
    print("%d of %d cases differ" % (bad, len(args.cases.split(","))))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
