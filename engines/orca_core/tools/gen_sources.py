"""
gen_sources.py - the list of Orca engine source files to compile.

    python gen_sources.py <orca source tree> <cuts.txt> <output sources.cmake> [report.md]

Reads the two source lists in <orca>/src/libslic3r/CMakeLists.txt (the engine, and the small CGAL library) so that we never keep a
copy of Orca's list, removes what cuts.txt names, and writes CMake variables with absolute paths.
"""
import fnmatch
import os
import re
import sys


def entries(text, name):
    m = re.search(r"(?:set\(%s|add_library\(%s STATIC)(.*?)\n\)" % (name, name), text, re.S)
    if not m:
        raise SystemExit("cannot find %s in Orca's CMakeLists.txt" % name)
    out = []
    for line in m.group(1).splitlines():
        line = line.split("#")[0].strip()
        for tok in line.split():
            if tok.startswith(("${", "\"")) or tok == "STATIC":
                continue
            out.append(tok)
    return out


def read_cuts(path):
    pats = []
    for line in open(path, encoding="utf-8"):
        raw = line.rstrip("\n")
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        pat, _, why = raw.partition("#")
        pats.append((pat.strip(), why.strip()))
    return pats


def main(argv):
    orca, cuts_file, out_cmake = argv[1:4]
    report = argv[4] if len(argv) > 4 else None
    src = os.path.join(orca, "src", "libslic3r")
    text = open(os.path.join(src, "CMakeLists.txt"), encoding="utf-8").read()
    cuts = read_cuts(cuts_file)
    engine = [e for e in entries(text, "lisbslic3r_sources")]
    cgal = [e for e in entries(text, "libslic3r_cgal")]
    kept, cut = {"engine": [], "cgal": []}, []
    for label, lst in (("engine", engine), ("cgal", cgal)):
        for f in lst:
            if not f.endswith((".cpp", ".c", ".cc")):
                continue
            hit = next((why for pat, why in cuts if fnmatch.fnmatch(f, pat)), None)
            if hit is not None:
                cut.append((f, hit))
            else:
                kept[label].append(f)
            if not os.path.isfile(os.path.join(src, f)) and hit is None:
                raise SystemExit("listed but missing on disk: " + f)
    with open(out_cmake, "w", encoding="utf-8", newline="\n") as o:
        o.write("# generated by gen_sources.py; do not edit\n")
        for label, var in (("engine", "ORCA_CORE_SOURCES"), ("cgal", "ORCA_CORE_CGAL_SOURCES")):
            o.write("set(%s\n" % var)
            for f in kept[label]:
                o.write('    "%s/%s"\n' % (src.replace("\\", "/"), f))
            o.write(")\n")
    if report:
        by = {}
        for f, why in cut:
            by.setdefault(why, []).append(f)
        with open(report, "w", encoding="utf-8") as r:
            r.write("# Source files left out\n\n%d of %d .cpp files kept (%d engine, %d CGAL)\n\n"
                    % (len(kept["engine"]) + len(kept["cgal"]), len(kept["engine"]) + len(kept["cgal"]) + len(cut),
                       len(kept["engine"]), len(kept["cgal"])))
            for why, fs in by.items():
                r.write("- %s: %d (%s)\n" % (why, len(fs), ", ".join(fs[:6]) + (", ..." if len(fs) > 6 else "")))
    print("engine %d files, cgal %d files, cut %d" % (len(kept["engine"]), len(kept["cgal"]), len(cut)))


if __name__ == "__main__":
    main(sys.argv)
